# ============================================================================
# GeneratePhantomBridgeIIDs.ps1
# ----------------------------------------------------------------------------
# 從 cppwinrt 產出的 PhantomBridge.0.h 解析 WinRT 介面 IID，產生 C# 端使用的
# 常數檔。IDL 變更 → IID 自動同步，避免手動抄 GUID 抄錯。
#
# 標頭內目標格式（示意；換行後可能有空白）：
#   template <> inline constexpr guid guid_v<winrt::PhantomBridge::IPhantomBridgeFactory>
#     { 0x27E89D6D,0xB3FF,0x50D2,{ 0xB5,0x05,0xA8,0x9B,0x63,0x35,0x3F,0x82 } };
#
# 策略：以 regex 抓第一個 guid_v<...IPhantomBridgeFactory> 後接的 4 個 hex 群組，
# 組成 {XXXXXXXX-XXXX-XXXX-XXXX-XXXXXXXXXXXX}。
# ============================================================================

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string] $HeaderPath,
    [Parameter(Mandatory = $true)] [string] $OutputPath
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path $HeaderPath)) {
    throw "PhantomBridge.0.h not found: $HeaderPath"
}

$content = Get-Content -Raw -LiteralPath $HeaderPath

# 介面名 → 期望輸出常數名（C# 端 [Guid("...")] 用）
$interfaces = @{
    'IPhantomBridgeFactory' = 'IPhantomBridgeFactory'
}

$entries = New-Object System.Collections.Generic.List[string]

foreach ($iface in $interfaces.Keys) {
    # guid_v<winrt::PhantomBridge::IFACE>{ 0xD1, 0xD2, 0xD3, { 0xB1, 0xB2, ..., 0xB8 } }
    # \s* 允許跨行；hex 接受 1~8 碼以對應 cppwinrt 可能省略前導零
    $byteRe = '0x([0-9A-Fa-f]{1,2})'
    $sep = '\s*,\s*'
    $byteGroup = "$byteRe$sep$byteRe$sep$byteRe$sep$byteRe$sep$byteRe$sep$byteRe$sep$byteRe$sep$byteRe"
    $pattern = 'guid_v<\s*winrt::PhantomBridge::' + [regex]::Escape($iface) +
               '\s*>\s*\{\s*0x([0-9A-Fa-f]{1,8})\s*,\s*0x([0-9A-Fa-f]{1,4})\s*,\s*0x([0-9A-Fa-f]{1,4})\s*,\s*\{\s*' +
               $byteGroup +
               '\s*\}\s*\}'

    $m = [regex]::Match($content, $pattern)
    if (-not $m.Success) {
        throw "Failed to parse IID for $iface in $HeaderPath. Header format may have changed."
    }

    $d1 = ([Convert]::ToUInt32($m.Groups[1].Value, 16)).ToString('X8')
    $d2 = ([Convert]::ToUInt16($m.Groups[2].Value, 16)).ToString('X4')
    $d3 = ([Convert]::ToUInt16($m.Groups[3].Value, 16)).ToString('X4')
    $b1 = ([Convert]::ToByte($m.Groups[4].Value, 16)).ToString('X2')
    $b2 = ([Convert]::ToByte($m.Groups[5].Value, 16)).ToString('X2')
    $b3 = ([Convert]::ToByte($m.Groups[6].Value, 16)).ToString('X2')
    $b4 = ([Convert]::ToByte($m.Groups[7].Value, 16)).ToString('X2')
    $b5 = ([Convert]::ToByte($m.Groups[8].Value, 16)).ToString('X2')
    $b6 = ([Convert]::ToByte($m.Groups[9].Value, 16)).ToString('X2')
    $b7 = ([Convert]::ToByte($m.Groups[10].Value, 16)).ToString('X2')
    $b8 = ([Convert]::ToByte($m.Groups[11].Value, 16)).ToString('X2')

    $guidStr = "$d1-$d2-$d3-$b1$b2-$b3$b4$b5$b6$b7$b8"
    $constName = $interfaces[$iface]
    $entries.Add("        public const string $constName = `"$guidStr`";")
}

$body = $entries -join "`r`n"

$output = @"
// <auto-generated>
//     由 Build\GeneratePhantomBridgeIIDs.ps1 從 PhantomBridge.0.h 解析產生。
//     請勿手動編輯——IDL 變更後重新建置 PhantomBridge → PhantomLink 即可同步。
// </auto-generated>

namespace OmniConsole.PhantomLink.Services
{
    internal static class PhantomBridgeIIDs
    {
$body
    }
}
"@

# 只在內容變動時寫檔，避免每次建置都觸動增量編譯
$writeNeeded = $true
if (Test-Path -LiteralPath $OutputPath) {
    $existing = Get-Content -Raw -LiteralPath $OutputPath
    if ($existing -eq $output) { $writeNeeded = $false }
}

if ($writeNeeded) {
    $dir = Split-Path -Parent $OutputPath
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    Set-Content -LiteralPath $OutputPath -Value $output -Encoding UTF8 -NoNewline
    Write-Host "Generated: $OutputPath"
} else {
    Write-Host "Up-to-date: $OutputPath"
}
